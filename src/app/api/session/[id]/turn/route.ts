import { NextResponse } from 'next/server';
import { z } from 'zod';

import { agentModel } from '@/lib/models';
import { callAnthropic } from '@/server/agent';
import { errorResponse, handled, ownedSession, rateLimit, requestLocale, resolveToday } from '@/server/http';
import { TURN_BUDGET_MS } from '@/lib/turnBudget';
import { chatBreaker } from '@/server/breakers';
import { askJev, jevCostMicrocents } from '@/server/jev';
import { getSightsFinder } from '@/server/sights';
import { getSupplier } from '@/server/supplier';
import { runTurn, type TurnEvent } from '@/server/turn';
import { isoDate } from '@/lib/isoDate';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';
export const maxDuration = 300;

const payload = z
  .object({
    message: z.string().trim().min(1).max(1000),
    /** Generated by the client once per send; a retry reuses it. */
    idempotencyKey: z.string().min(8).max(100),
    today: isoDate,
  })
  .strict();

/**
 * One chat message. The answer is a Server-Sent Events stream of progress;
 * the turn itself runs to completion whether or not the client stays, and is
 * read back from GET …/turns or the session view.
 */
export const POST = handled(async (req: Request, ctx: { params: { id: string } }) => {
  const parsed = payload.safeParse(await req.json().catch(() => null));
  if (!parsed.success) return errorResponse('invalid_request', 400);
  const session = await ownedSession(ctx.params.id);
  if (session instanceof NextResponse) return session;
  const limited = await rateLimit('turn', 30);
  if (limited) return limited;
  // Before the turn record and before any paid call. Fails closed (server/breakers.ts).
  const breaker = await chatBreaker(new Date());
  if (breaker.open) {
    console.error('[turn] breaker open:', breaker.reason);
    return errorResponse('circuit_open', 503);
  }
  // The platform kills this function at maxDuration; the turn stops itself first and says so (lib/turnBudget.ts).
  const deadline = Date.now() + TURN_BUDGET_MS;
  const today = resolveToday(parsed.data.today, new Date());
  if (!today) return errorResponse('bad_date', 400);
  const locale = requestLocale();

  const encoder = new TextEncoder();
  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      let open = true;
      const send = (event: TurnEvent | { type: 'error'; code: 'turn_failed' }) => {
        if (!open) return;
        try {
          controller.enqueue(encoder.encode(`data: ${JSON.stringify(event)}\n\n`));
        } catch {
          open = false; // the client left; the turn carries on
        }
      };
      void runTurn({
        session,
        message: parsed.data.message,
        idempotencyKey: parsed.data.idempotencyKey,
        deps: {
          supplier: getSupplier({ sessionId: session.id, userId: session.userId, language: locale }),
          findSights: getSightsFinder({ sessionId: session.id, userId: session.userId, language: locale }),
          askJev,
          jevCost: jevCostMicrocents,
          callModel: callAnthropic,
          model: agentModel(),
          now: () => new Date(),
          today,
          deadline,
          locale,
        },
        emit: send,
      })
        .catch((err) => {
          console.error('[turn] route', err);
          send({ type: 'error', code: 'turn_failed' });
        })
        .finally(() => {
          if (!open) return;
          open = false;
          try {
            controller.close();
          } catch {
            // already closed by the client
          }
        });
    },
  });

  return new Response(stream, {
    headers: { 'Content-Type': 'text/event-stream; charset=utf-8', 'Cache-Control': 'no-cache, no-transform', Connection: 'keep-alive' },
  });
});
